#!/usr/bin/env python3
"""
Plot filtered *_load_slim.csv files.

The slim CSV is generated by filter_servo_load_run.py and contains columns like:
  M02_abs, M02_load, J02_deg

Examples:
  python desktop/visualize/plot_servo_load_slim.py --csv run_data/hand_run_xxx_load_slim.csv --motors M02
  python desktop/visualize/plot_servo_load_slim.py --csv run_data/foo_load_slim.csv --motors M02 --joint J02 --save
  python desktop/visualize/plot_servo_load_slim.py --csv C:/Users/g8765/Downloads/foo_load_slim.csv --motors M02 --x abs --save
  python desktop/visualize/plot_servo_load_slim.py --csv foo_load_slim.csv --all --save
"""

from __future__ import annotations

import argparse
import csv
import math
import os
import re
import sys
from datetime import datetime
from typing import Dict, Iterable, List, Sequence


def _safe_float(value) -> float:
    try:
        out = float(value)
        if math.isfinite(out):
            return out
    except Exception:
        pass
    return float("nan")


def _safe_int(value) -> int:
    try:
        return int(float(value))
    except Exception:
        return 0


def _load_without_direction_bit(value) -> int:
    raw = _safe_int(value)
    return abs(raw) & 0x03FF


def _read_rows(csv_path: str) -> tuple[List[str], List[Dict[str, str]]]:
    with open(csv_path, "r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        return list(reader.fieldnames or []), list(reader)


def _parse_motor_token(token: str) -> int:
    token = str(token).strip().upper()
    if token.startswith("M"):
        token = token[1:]
    return int(token)


def _parse_motor_list(text: str) -> List[int]:
    motors: List[int] = []
    for piece in str(text or "").replace(";", ",").split(","):
        piece = piece.strip()
        if not piece:
            continue
        motor = _parse_motor_token(piece)
        if motor not in motors:
            motors.append(motor)
    return motors


def _parse_joint_token(token: str) -> int:
    token = str(token).strip().upper()
    if token.startswith("J"):
        token = token[1:]
    return int(token)


def _parse_joint_list(text: str) -> List[int]:
    joints: List[int] = []
    for piece in str(text or "").replace(";", ",").split(","):
        piece = piece.strip()
        if not piece:
            continue
        joint = _parse_joint_token(piece)
        if joint not in joints:
            joints.append(joint)
    return joints


def _motors_from_columns(fieldnames: Iterable[str]) -> List[int]:
    motors = set()
    pattern = re.compile(r"^M(\d{2})_load$")
    for name in fieldnames:
        match = pattern.match(name)
        if match:
            motors.add(int(match.group(1)))
    return sorted(motors)


def _resolve_motors(fieldnames: Sequence[str], motors_text: str, plot_all: bool) -> List[int]:
    motors = _motors_from_columns(fieldnames) if plot_all or not motors_text else _parse_motor_list(motors_text)
    if not motors:
        raise ValueError("No motors selected. Use --motors M02 or --all.")
    missing = [motor for motor in motors if f"M{motor:02d}_load" not in fieldnames]
    if missing:
        missing_text = ", ".join(f"M{motor:02d}" for motor in missing)
        raise ValueError(f"Selected motors are not in this slim CSV: {missing_text}")
    return motors


def _series(rows: Sequence[Dict[str, str]], key: str) -> List[float]:
    return [_safe_float(row.get(key, "")) for row in rows]


def _time_series(rows: Sequence[Dict[str, str]]) -> List[float]:
    raw: List[float] = []
    for row in rows:
        text = str(row.get("host_time", "") or "").strip()
        try:
            raw.append(datetime.fromisoformat(text).timestamp())
        except Exception:
            raw.append(float("nan"))
    finite = [value for value in raw if math.isfinite(value)]
    if not finite:
        return [float(i) for i in range(len(rows))]
    t0 = finite[0]
    last = 0.0
    out: List[float] = []
    for value in raw:
        if math.isfinite(value):
            last = value - t0
        out.append(last)
    return out


def _joint_columns(fieldnames: Sequence[str], joints: Sequence[int]) -> List[str]:
    if joints:
        return [f"J{joint:02d}_deg" for joint in joints if f"J{joint:02d}_deg" in fieldnames]
    return [name for name in fieldnames if re.match(r"^J\d{2}_deg$", name)]


def _ensure_matplotlib():
    try:
        import matplotlib.pyplot as plt
        return plt
    except Exception as exc:
        raise RuntimeError("matplotlib is required for plotting.") from exc


def _auto_save_path(csv_path: str, motors: Sequence[int], x_axis: str) -> str:
    base, _ext = os.path.splitext(os.path.abspath(csv_path))
    motor_label = "_".join(f"M{motor:02d}" for motor in motors)
    return f"{base}_{motor_label}_load_vs_{x_axis}.png"


def plot_slim_csv(csv_path: str,
                  motors: Sequence[int],
                  joints: Sequence[int],
                  x_axis: str,
                  save_path: str,
                  show_joint: bool) -> None:
    fieldnames, rows = _read_rows(csv_path)
    if not rows:
        raise ValueError("CSV has no data rows.")

    plt = _ensure_matplotlib()
    fig, axes_obj = plt.subplots(2 if show_joint else 1, 1, figsize=(11, 7 if show_joint else 5.5), sharex=True)
    if hasattr(axes_obj, "ravel"):
        axes = list(axes_obj.ravel())
    elif isinstance(axes_obj, (list, tuple)):
        axes = list(axes_obj)
    else:
        axes = [axes_obj]

    time_values = _time_series(rows)
    title_parts = [os.path.basename(csv_path)]
    scope = rows[0].get("active_scope_label", "")
    if scope:
        title_parts.append(scope)

    for motor in motors:
        label = f"M{motor:02d}"
        if x_axis == "abs":
            x = _series(rows, f"{label}_abs")
            xlabel = f"{label} abs" if len(motors) == 1 else "motor abs"
        else:
            x = time_values
            xlabel = "elapsed time (s)"

        load = [_load_without_direction_bit(row.get(f"{label}_load", "")) for row in rows]
        axes[0].plot(x, load, linewidth=1.3, label=f"{label} load")
        axes[0].scatter(x, load, s=7, alpha=0.35)

    axes[0].set_title(" | ".join(title_parts))
    axes[0].set_ylabel("load magnitude (raw & 0x03FF)")
    axes[0].grid(True, alpha=0.25)
    axes[0].legend(loc="best")

    if show_joint and len(axes) > 1:
        for key in _joint_columns(fieldnames, joints):
            x = _series(rows, f"M{motors[0]:02d}_abs") if x_axis == "abs" and len(motors) == 1 else time_values
            axes[1].plot(x, _series(rows, key), linewidth=1.2, label=key)
        axes[1].set_ylabel("joint angle (deg)")
        axes[1].grid(True, alpha=0.25)
        axes[1].legend(loc="best")

    axes[-1].set_xlabel(xlabel)
    fig.tight_layout()

    if save_path:
        fig.savefig(save_path, dpi=150)
        print(f"Saved: {save_path}")
    else:
        plt.show()


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot motor load curves from *_load_slim.csv.")
    parser.add_argument("--csv", required=True, help="Filtered *_load_slim.csv path.")
    parser.add_argument("--motors", default="", help="Comma-separated motors, for example M02,M03.")
    parser.add_argument("--joint", default="", help="Optional joint angle columns to plot, for example J02 or J02,J03.")
    parser.add_argument("--all", action="store_true", help="Plot every Mxx_load column in the slim CSV.")
    parser.add_argument("--x", choices=("abs", "time"), default="abs", help="X axis: motor abs or elapsed time.")
    parser.add_argument("--no-joint", action="store_true", help="Do not plot joint angle context.")
    parser.add_argument("--save", nargs="?", const="AUTO", default="", help="Save PNG. Optional explicit output path.")
    args = parser.parse_args()

    try:
        csv_path = os.path.abspath(args.csv)
        fieldnames, _rows = _read_rows(csv_path)
        motors = _resolve_motors(fieldnames, args.motors, args.all)
        joints = _parse_joint_list(args.joint)
        if args.save == "AUTO":
            save_path = _auto_save_path(csv_path, motors, args.x)
        else:
            save_path = os.path.abspath(args.save) if args.save else ""
        print(f"Using CSV: {csv_path}")
        print(f"Motors: {', '.join(f'M{motor:02d}' for motor in motors)}")
        if joints:
            print(f"Joints: {', '.join(f'J{joint:02d}' for joint in joints)}")
        plot_slim_csv(csv_path, motors, joints, args.x, save_path, not args.no_joint)
        return 0
    except Exception as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
