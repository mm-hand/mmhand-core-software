#!/usr/bin/env python3
"""扫描 desktop/core 的用户可见拒绝消息，生成离线安全目录。

职责：静态列出上位机所有“会向用户解释的失败点”及其 issue 归类。
线程：脚本单线程；不启动 UI、不连接设备。
输入：desktop/core/**/*.py 的 AST。
输出：docs/desktop-safety-catalog.md（--check 时只比对）。
状态所有权：无运行期状态。
禁止依赖：禁止导入 UI、串口或改变任何判定逻辑。

上位机没有声明式门禁源；拒绝消息是唯一可静态枚举的痕迹。收集
OperationResult/IssueMessage/return False 的字符串（f-string 记为模板），
再交给 user_issues.operation_issue 归类，因此能直接看出哪些失败仍落兜底。
"""

from __future__ import annotations

import argparse
import ast
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
SOURCE = ROOT / "desktop" / "core"
OUTPUT = ROOT / "docs" / "desktop-safety-catalog.md"
FALLBACK = "HOST_ACTION_FAILED"


def _text(node: ast.AST) -> str:
    """常量原样返回；f-string 的插值位置记为模板占位符。"""
    if isinstance(node, ast.Constant):
        return node.value if isinstance(node.value, str) else ""
    if isinstance(node, ast.JoinedStr):
        return "".join(value.value if isinstance(value, ast.Constant) else "{…}"
                       for value in node.values)
    return ""


def _rejections(path: Path):
    """按源码顺序产出 (行号, 消息)；只认会向用户解释的失败形态。"""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            if node.func.id == "OperationResult" and len(node.args) >= 3:
                argument = node.args[2]
            elif node.func.id == "IssueMessage" and node.args:
                argument = node.args[0]
            else:
                continue
            text = _text(argument)
            if text:
                yield node.lineno, text
        elif (isinstance(node, ast.Return) and isinstance(node.value, ast.Tuple)
              and len(node.value.elts) >= 2
              and isinstance(node.value.elts[0], ast.Constant)
              and node.value.elts[0].value is False):
            text = _text(node.value.elts[1])
            if text:
                yield node.lineno, text
        elif (isinstance(node, ast.Assign) and len(node.targets) == 1
              and isinstance(node.targets[0], ast.Name) and node.targets[0].id == "reason"):
            # Direct 准入把拒绝原因暂存到 reason，再随返回值一起抛出。
            # 单 token 的 snake_case 是内部原因码，不是用户消息。
            text = _text(node.value)
            if text and " " in text:
                yield node.lineno, text


def render() -> str:
    from desktop.core.user_issues import operation_issue

    files = {}
    for path in sorted(SOURCE.rglob("*.py")):
        rows = sorted(_rejections(path))
        if rows:
            files[path.relative_to(ROOT).as_posix()] = rows
    total = sum(len(rows) for rows in files.values())
    codes = Counter(operation_issue(text).code for rows in files.values() for _, text in rows)
    texts = Counter(text for rows in files.values() for _, text in rows)
    duplicates = [(text, count) for text, count in texts.items() if count > 1]
    lines = [
        "# Desktop safety catalog",
        "",
        "Generated by `tools/generate_desktop_safety_catalog.py`; do not edit.",
        "",
        f"{total} rejection messages, {codes[FALLBACK]} fall back to `{FALLBACK}` "
        "(the app cannot name the cause).",
        "",
        "Static scan only: gates that fail silently, or forward `return False, message`,",
        "are not listed. f-string messages are templates.",
        "",
    ]
    for name, rows in files.items():
        lines += [f"## {name}", "", "| Line | Message | Issue |", "| --- | --- | --- |"]
        for line, text in rows:
            code = operation_issue(text).code
            lines.append(f"| {line} | {text.replace('|', '/')} | {code}"
                         f"{' ⚠ fallback' if code == FALLBACK else ''} |")
        lines.append("")
    lines += ["## Duplicate messages", ""]
    lines += [f"- ×{count} `{text}`" for text, count in duplicates] or ["- none"]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="生成/检查上位机安全目录")
    parser.add_argument("--check", action="store_true", help="只检查生成文件是否最新")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"stale generated file: {OUTPUT}")
            return 1
        print(f"desktop safety catalog is current ({OUTPUT.name})")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"generated {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
