#!/usr/bin/env python3
"""Generate the P4 URDF joint-limit table from the desktop mapping config."""

from __future__ import annotations

import argparse
import json
import math
import struct
import sys
import zlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "desktop" / "resources" / "config" / "urdf_joint_mapping_v2.json"
DEFAULT_OUTPUT = (
    ROOT
    / "ESP32-P4"
    / "ServoBoardMain"
    / "src"
    / "generated"
    / "UrdfJointLimits.generated.h"
)
EXPECTED_JOINT_COUNT = 21


def load_mapping(path: Path) -> tuple[int, int, str, list[tuple[int, float, float]]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    version = int(data.get("feedback_mapping_version", 0))
    manual_scaled_version = int(data.get("manual_scaled_mapping_version", 0))
    mapping_id = str(data.get("mapping_id", ""))
    joints = data.get("joints")
    if (version <= 0 or manual_scaled_version <= version or
            not mapping_id or not isinstance(joints, list)):
        raise ValueError("mapping version, mapping_id, or joints is invalid")
    if len(joints) != EXPECTED_JOINT_COUNT:
        raise ValueError(f"expected {EXPECTED_JOINT_COUNT} joints, got {len(joints)}")

    result: list[tuple[int, float, float]] = []
    for expected_index, item in enumerate(joints):
        if not isinstance(item, dict):
            raise ValueError(f"joint {expected_index} is not an object")
        joint_index = int(item.get("joint_index", -1))
        if joint_index != expected_index:
            raise ValueError(
                f"joint index order mismatch: expected {expected_index}, got {joint_index}"
            )
        limits = item.get("urdf_limit_deg")
        if not isinstance(limits, list) or len(limits) != 2:
            raise ValueError(f"joint {joint_index} urdf_limit_deg must have two values")
        lower, upper = float(limits[0]), float(limits[1])
        if not math.isfinite(lower) or not math.isfinite(upper) or lower >= upper:
            raise ValueError(f"joint {joint_index} has invalid URDF limits {limits}")
        result.append((joint_index, lower, upper))
    return version, manual_scaled_version, mapping_id, result


def mapping_crc32(version: int, joints: list[tuple[int, float, float]]) -> int:
    payload = bytearray(struct.pack(">BB", version & 0xFF, len(joints) & 0xFF))
    for joint_index, lower, upper in joints:
        payload.extend(struct.pack(">Bff", joint_index & 0xFF, lower, upper))
    return zlib.crc32(payload) & 0xFFFFFFFF


def render_header(version: int, manual_scaled_version: int, mapping_id: str,
                  joints: list[tuple[int, float, float]]) -> str:
    crc = mapping_crc32(version, joints)
    manual_scaled_crc = mapping_crc32(manual_scaled_version, joints)
    rows = "\n".join(
        f"    {{{lower:.6f}f, {upper:.6f}f}},  // J{joint_index:02d}"
        for joint_index, lower, upper in joints
    )
    return f"""// Generated by tools/generate_p4_urdf_limits.py. Do not edit manually.
// Source mapping: {mapping_id}
#ifndef URDF_JOINT_LIMITS_GENERATED_H
#define URDF_JOINT_LIMITS_GENERATED_H

#include <Arduino.h>

#include "../shared/TaskSharedData.h"

struct UrdfJointLimitDeg {{
    float minDeg;
    float maxDeg;
}};

static const uint8_t kUrdfFeedbackMappingVersion = {version};
static const uint32_t kUrdfJointLimitConfigCrc = 0x{crc:08X}UL;
static const uint8_t kManualScaledUrdfFeedbackMappingVersion = {manual_scaled_version};
static const uint32_t kManualScaledUrdfConfigCrc = 0x{manual_scaled_crc:08X}UL;
static const UrdfJointLimitDeg kUrdfJointLimits[ENCODER_TOTAL_NUM] = {{
{rows}
}};

static_assert(
    sizeof(kUrdfJointLimits) / sizeof(kUrdfJointLimits[0]) == ENCODER_TOTAL_NUM,
    "URDF joint limit table must match ENCODER_TOTAL_NUM");

#endif // URDF_JOINT_LIMITS_GENERATED_H
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if output is stale")
    args = parser.parse_args()

    try:
        version, manual_scaled_version, mapping_id, joints = load_mapping(args.input)
        rendered = render_header(version, manual_scaled_version, mapping_id, joints)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"URDF limit generation failed: {exc}", file=sys.stderr)
        return 2

    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except OSError:
            current = ""
        if current != rendered:
            print(f"generated header is stale: {args.output}", file=sys.stderr)
            return 1
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"generated {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
